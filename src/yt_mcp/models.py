"""Structured payloads returned by the MCP tools."""

from datetime import datetime

from pydantic import BaseModel, Field


class Channel(BaseModel):
    """A resolved YouTube channel."""

    id: str = Field(description="Channel id (UC...)")
    title: str = Field(description="Channel display name")
    handle: str | None = Field(default=None, description="Channel handle, e.g. @mkbhd")
    url: str = Field(description="Canonical channel URL")
    description: str = Field(default="", description="Channel description")
    subscriber_count: int | None = Field(
        default=None,
        description="Subscribers, or null when the channel hides the count",
    )
    video_count: int | None = Field(default=None, description="Public video count")
    uploads_playlist_id: str | None = Field(
        default=None,
        description="Playlist holding every public upload, used for listing",
    )


class Video(BaseModel):
    """A video, as returned by search and listing tools."""

    id: str = Field(description="Video id")
    title: str = Field(description="Video title")
    url: str = Field(description="Canonical watch URL")
    channel_id: str = Field(description="Owning channel id")
    channel_title: str = Field(description="Owning channel name")
    published_at: datetime | None = Field(default=None, description="Publish instant")
    duration: str | None = Field(
        default=None, description="Duration as MM:SS or H:MM:SS"
    )
    duration_seconds: int | None = Field(
        default=None, description="Duration in seconds"
    )
    is_short_form: bool = Field(
        default=False,
        description="Heuristic: duration is 60 seconds or less, i.e. likely a Short",
    )
    view_count: int | None = Field(default=None, description="Lifetime views")
    description_excerpt: str = Field(
        default="",
        description="First few lines of the description; use get_video_details for all",
    )


class VideoDetails(Video):
    """A video plus its full description and engagement counts."""

    description: str = Field(default="", description="Full description text")
    links: list[str] = Field(
        default_factory=list,
        description="Unique http(s) links found in the description, in order",
    )
    tags: list[str] = Field(default_factory=list, description="Creator-supplied tags")
    like_count: int | None = Field(default=None, description="Likes, when public")
    comment_count: int | None = Field(default=None, description="Comments, when public")
    has_captions: bool | None = Field(
        default=None,
        description="Whether YouTube reports captions for this video",
    )


class VideoList(BaseModel):
    """A page of videos belonging to one channel."""

    channel: Channel = Field(description="The channel the videos belong to")
    query: str | None = Field(default=None, description="Search terms, when searching")
    published_after: datetime | None = Field(
        default=None,
        description="Lower bound applied to publish dates",
    )
    published_before: datetime | None = Field(
        default=None,
        description="Upper bound applied to publish dates",
    )
    count: int = Field(description="Number of videos in this response")
    videos: list[Video] = Field(description="Videos, newest first unless reordered")
    truncated: bool = Field(
        default=False,
        description="True when more videos matched than max_results allowed",
    )


class Transcript(BaseModel):
    """A timestamped transcript."""

    video_id: str = Field(description="Video id")
    url: str = Field(description="Canonical watch URL")
    language: str = Field(description="Transcript language name")
    language_code: str = Field(description="Transcript language code, e.g. en")
    is_generated: bool = Field(
        description="True when auto-generated by YouTube rather than creator-supplied",
    )
    available_languages: list[str] = Field(
        default_factory=list,
        description="Language codes with a transcript for this video",
    )
    segment_count: int = Field(description="Number of timestamped lines returned")
    start_seconds: float = Field(description="Offset of the first returned line")
    end_seconds: float = Field(description="End offset of the last returned line")
    text: str = Field(
        description=(
            "Transcript as '[[MM:SS]](watch url with &t=seconds) text' lines, one "
            "per merged segment; each timestamp is a Markdown link that seeks to "
            "that moment, so quoting a line carries its own citation"
        ),
    )
